import { createRequire } from 'node:module';
const require = createRequire('/home/user/objectui-issue-12915/package.json');
const { chromium } = require('@playwright/test');
const [,, label, outDir, recordId] = process.argv;
const APP = 'http://localhost:5180';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
const page = await ctx.newPage();
const res = await page.request.post(`${APP}/api/v1/auth/sign-in/email`, { data: { email: 'admin@objectos.ai', password: 'admin123' } });
console.log('sign-in', res.status());
await page.goto(`${APP}/apps/showcase_app/showcase_invoice/record/${recordId}`);
await page.getByText('Unit Price').first().waitFor({ timeout: 90000 });
await page.waitForTimeout(2500);
const table = page.locator('table', { has: page.getByText('Unit Price') }).last();
await table.scrollIntoViewIfNeeded();
const rows = await table.locator('tr').allInnerTexts();
console.log('SCREEN rows:', JSON.stringify(rows));
await page.screenshot({ path: `${outDir}/${label}-screen.png`, fullPage: true });
await table.locator('xpath=ancestor::div[1]').screenshot({ path: `${outDir}/${label}-screen-table.png` }).catch((e) => console.log('table shot skipped', e.message.split('\n')[0]));
await page.emulateMedia({ media: 'print' });
await page.waitForTimeout(800);
const prow = await table.locator('tr').allInnerTexts();
console.log('PRINT rows:', JSON.stringify(prow));
await page.screenshot({ path: `${outDir}/${label}-print-preview.png`, fullPage: true });
await page.pdf({ path: `${outDir}/${label}-print.pdf`, format: 'A4', printBackground: true });
await browser.close();
